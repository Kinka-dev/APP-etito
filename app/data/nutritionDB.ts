export type FoodItem = {
  name: string;
  category: string;
  kcal: number;
  carbs: number;
  protein: number;
  fat: number;
};

export const flatNutritionDB: FoodItem[] = Object.entries(nutritionDB).flatMap(
  ([category, items]) =>
    Object.entries(items as Record<string, any>).map(([name, data]) => ({
      name,
      category,
      kcal: data.kcal,
      carbs: data.carbs ?? 0,
      protein: data.protein ?? 0,
      fat: data.fat ?? 0,
    })),
);

export const calculateMacros = (foodName: string, grams: number) => {
  const item = flatNutritionDB.find(
    (f) => f.name.toLowerCase() === foodName.toLowerCase(),
  );
  if (!item) return null;

  const factor = grams / 100;

  return {
    kcal: item.kcal * factor,
    carbs: item.carbs * factor,
    protein: item.protein * factor,
    fat: item.fat * factor,
  };
};
